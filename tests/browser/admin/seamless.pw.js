import {test, expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {fixture, origin} from '../../../tools/admin/test-fixture.js';
import {handle} from '../../../admin/worker.js';
import {digest} from '../../../intake/worker.js';

const main = 'a'.repeat(40);
const fits = page => expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);

for (const width of [390, 1280]) test(`cleanup and hands-off publication tracking at ${width}px`, async ({page, context}) => {
  const x = await fixture(), original = globalThis.fetch; globalThis.fetch = x.fetcher;
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  try {
    await x.login();
    await page.setViewportSize({width, height: 900});
    await x.seed({title: 'Original'}); await x.seed({title: 'Copy'});
    await x.seed({title: 'Spam A', url: 'https://fiction.example.org/a'}); await x.seed({title: 'Spam B', url: 'https://fiction.example.org/b'});
    await x.seed({title: 'Keep', url: 'https://fiction.example.org/keep'});
    const count = () => x.db.prepare('SELECT count(*) n FROM submissions').get().n;
    const time = Math.floor(Date.now() / 1000);
    const insert = async (id, state, more = {}) => {
      const pkg = JSON.stringify({project_id: 'ext-abcdefghijkl', operation: 'submission', files: [], policy: {}, listing: {title: 'Tracked project', description: 'A fictional tracked project.'}}), hash = await digest(pkg);
      const row = {id, submission_id: null, revision: null, project_id: 'ext-abcdefghijkl', operation: 'submission', payload: '{"value":{}}', state, version: 1, package: pkg, digest: hash, approved_digest: null, pr: null, created: time, updated: time, ...more};
      x.db.prepare('INSERT INTO admin_reviews(id,submission_id,revision,project_id,operation,payload,state,version,package,digest,approved_digest,pr,created,updated) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?)').run(...Object.values(row));
      return row;
    };
    await context.route(origin + '/**', async route => {
      const req = route.request(), data = req.postData();
      const response = await handle(new Request(req.url(), {method: req.method(), headers: {...req.headers(), 'Cf-Access-Jwt-Assertion': x.token}, ...(data ? {body: data} : {})}), x.env);
      await route.fulfill({status: response.status, headers: Object.fromEntries(response.headers), body: Buffer.from(await response.arrayBuffer())});
    });
    await page.clock.install();
    await page.goto(origin);
    await expect(page.locator('#queue-count')).toHaveText('5 submissions');
    await expect(page.locator('#queue-summary')).toHaveText('New submission: 5');
    const card = title => page.locator('.item-card').filter({has: page.getByRole('heading', {name: title, exact: true})});
    await expect(card('Original').getByText('Possible duplicate of submission 2')).toBeVisible();
    await card('Original').locator('summary').click();
    await expect(card('Original').locator('.compare li')).toHaveCount(2);
    await expect(card('Original').locator('.compare')).toContainText('#1 Original (this one)');
    await expect(card('Original').locator('.compare')).toContainText('#2 Copy');
    await expect(card('Original').locator('.compare').getByRole('link', {name: 'https://fiction.example.org/project'})).toHaveCount(2);
    await fits(page);
    expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
    await page.screenshot({path: `.review/025/inbox-${width}.png`, fullPage: true});
    await card('Original').getByRole('button', {name: 'Delete duplicate #2', exact: true}).click();
    await expect(page.getByRole('heading', {name: 'Delete permanently?'})).toBeVisible();
    await expect(page.locator('#confirmation-text')).toContainText('Permanently delete submission #2 Copy?');
    expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
    await page.getByRole('button', {name: 'Cancel', exact: true}).click();
    expect(count()).toBe(5);
    await card('Original').getByRole('button', {name: 'Delete duplicate #2', exact: true}).click();
    await page.getByRole('button', {name: 'Delete submission', exact: true}).click();
    await expect(page.locator('#notice')).toHaveText('Deleted 1 submission.');
    await expect(card('Copy')).toHaveCount(0); await expect(card('Original')).toHaveCount(1);
    await expect(card('Original').getByText('Possible duplicate')).toHaveCount(0);
    await expect(page.getByRole('button', {name: 'Delete selected', exact: true})).toBeDisabled();
    await page.getByLabel('Select submission 3', {exact: true}).check(); await page.getByLabel('Select submission 4', {exact: true}).check();
    await expect(page.locator('#selected-count')).toHaveText('2 selected');
    await x.seed({title: 'Arrived later', url: 'https://fiction.example.org/late'});
    await page.getByRole('button', {name: 'Delete selected', exact: true}).click();
    await expect(page.locator('#confirmation-text')).toContainText('Permanently delete 2 submissions?');
    await page.getByRole('button', {name: 'Delete 2 submissions', exact: true}).click();
    await expect(page.locator('#notice')).toHaveText('Deleted 2 submissions.');
    expect(x.db.prepare('SELECT id FROM submissions ORDER BY id').all().map(r => r.id)).toEqual([1, 5, 6]);
    await expect(page.locator('#selected-count')).toHaveText('0 selected');
    await expect(card('Arrived later')).toHaveCount(1);
    await page.getByRole('button', {name: 'Select all 3 matching', exact: true}).click();
    await expect(page.locator('#selected-count')).toHaveText('3 selected');
    await page.getByRole('button', {name: 'Clear selection', exact: true}).click();
    await expect(page.locator('#selected-count')).toHaveText('0 selected');
    await page.getByRole('button', {name: 'Review submission 5', exact: true}).click();
    await expect(page.getByRole('button', {name: 'Delete submission', exact: true})).toBeVisible();
    await fits(page);

    const r = await insert('t'.repeat(24), 'ready', {submission_id: 1, revision: 1});
    await page.getByRole('button', {name: 'Publication reviews', exact: true}).click();
    await page.getByLabel('I reviewed the exact content', {exact: false}).check();
    await page.getByRole('button', {name: 'Approve & Expedite', exact: true}).click(); await page.getByRole('button', {name: 'Confirm', exact: true}).click();
    const status = page.locator('#publication-status');
    await expect(status).toContainText('Publication is starting.');
    await expect(page.getByRole('button', {name: 'Publish now'})).toHaveCount(0);
    await expect(page.getByRole('button', {name: /Prepare protected|Verify PR/})).toHaveCount(0);
    expect(x.state.dispatched.map(d => d.inputs.action)).toEqual(['publish']);
    await x.processCall(r.id, '/claim', {action: 'publish'});
    expect((await x.processCall(r.id, '/published-pr', {pr: 42, auto_merge: 'enabled'})).status).toBe(200);
    x.state.pr = {number: 42, state: 'open', merged: false, mergeable_state: 'blocked', auto_merge: {merge_method: 'squash'}, head: {sha: main}, html_url: 'https://github.com/fictional/hub/pull/42'};
    x.state.checks = [{name: 'test', status: 'in_progress', conclusion: null}];
    await page.clock.fastForward(21000);
    await expect(status).toContainText('Automated checks are running.');
    await expect(status.locator('[aria-current=step]')).toHaveText('Waiting for checks');
    x.state.pr = {...x.state.pr, state: 'closed', merged: true, merge_commit_sha: main};
    await page.clock.fastForward(21000);
    await expect(status).toContainText('The approved change is being published.');
    await expect(status.locator('.review-stage')).toHaveCount(1);
    x.state.manifest = {build_commit: main}; x.state.runs = [{id: 1, head_sha: main, event: 'push', status: 'completed', conclusion: 'success', run_attempt: 1}];
    x.state.jobs = ['synchronize', 'backup', 'anchor', 'publish', 'website', 'deploy-website'].map(name => ({name, conclusion: 'success'})); x.state.projects = [{id: 'ext-abcdefghijkl'}];
    await page.clock.fastForward(21000);
    await expect(status).toContainText('The change is live.');
    await expect(status.getByRole('link', {name: 'Open the live page'})).toHaveAttribute('href', 'https://site.example/projects/ext-abcdefghijkl/');
    await expect(page.locator('#review-list .tag')).toHaveText('Published');
    const polls = x.state.github.length;
    await page.clock.fastForward(65000);
    expect(x.state.github.length).toBe(polls);
    expect(x.state.dispatched.length).toBe(1);
    await expect(page.locator('body')).not.toContainText(/pr-open|awaiting-deployment|dispatch-failed/);
    await fits(page);
    expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
    await page.screenshot({path: `.review/025/published-${width}.png`, fullPage: true});

    await page.reload();
    await expect(card('Original').locator('.tag')).toHaveText('Published');
    await page.getByRole('button', {name: 'Publication reviews', exact: true}).click();
    await expect(page.locator('#publication-status')).toContainText('The change is live.');

    const closed = await insert('u'.repeat(24), 'pr-open', {pr: 43, created: time + 5, approved_digest: 'x'});
    x.state.pr = {number: 43, state: 'closed', merged: false, head: {sha: main}, html_url: 'https://github.com/fictional/hub/pull/43'};
    await page.getByRole('button', {name: 'Publication reviews', exact: true}).click();
    await page.locator('#review-list .review-item').first().click();
    await expect(page.locator('#publication-status')).toContainText('The publication request was closed before anything was published.');
    await expect(page.locator('#publication-status h3')).toHaveText('Publication: Needs attention');
    await expect(page.getByRole('button', {name: 'Prepare a new review', exact: true})).toBeVisible();
    await fits(page);
    expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
    await page.screenshot({path: `.review/025/attention-${width}.png`, fullPage: true});
    await page.getByRole('button', {name: 'Discard unfinished review', exact: true}).click(); await page.getByRole('button', {name: 'Confirm', exact: true}).click();
    await expect(page.locator('#notice')).toHaveText('Unfinished review discarded.');
    expect(x.db.prepare('SELECT state FROM admin_reviews WHERE id=?').get(closed.id).state).toBe('discarded');
    await expect(page.locator('#review-list .review-item').first().locator('.tag')).toHaveText('Discarded');
    expect(errors).toEqual([]);
  } finally { globalThis.fetch = original; x.db.close(); }
});
